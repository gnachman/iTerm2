#!/bin/bash

function die {
  echo $1
  exit
}

branch() {
  local output=$(git symbolic-ref -q --short HEAD)
    if [ $? -eq 0 ]; then
        echo "${output}"
    fi
}

set -x

# The shell_integration Makefile uses envsubst (from gettext) to embed it2.py into
# each script. Homebrew installs gettext keg-only, so put its bin on PATH.
GETTEXT_BIN=$(brew --prefix gettext 2>/dev/null)/bin
test -d "$GETTEXT_BIN" && PATH="$GETTEXT_BIN:$PATH"
command -v envsubst >/dev/null || die "envsubst not found; run 'make setup' (installs gettext)"

SUBMODULE=$PWD/submodules/iTerm2-shell-integration
test -d $SUBMODULE || die No $SUBMODULE directory
pushd $SUBMODULE
if [ $(branch) != main ]; then
  echo "Not on main. The current branch is $(branch)."
fi
popd

(cd submodules/iTerm2-shell-integration/ && make)
# The submodule's top-level Makefile only handles utilities (it2ssh). The bash
# integration script is assembled from source/bash.0, bash-preexec.sh, and
# source/bash.1 by the shell_integration/Makefile, so it has to be invoked
# separately or edits to source/bash.{0,1} silently never reach the assembled
# `bash` file (and therefore never reach Resources/).
(cd submodules/iTerm2-shell-integration/shell_integration/ && make)
cp $SUBMODULE/shell_integration/bash  Resources/shell_integration/iterm2_shell_integration.bash
cp $SUBMODULE/shell_integration/fish  Resources/shell_integration/iterm2_shell_integration.fish
cp $SUBMODULE/shell_integration/tcsh  Resources/shell_integration/iterm2_shell_integration.tcsh
cp $SUBMODULE/shell_integration/xonsh Resources/shell_integration/iterm2_shell_integration.xonsh
cp $SUBMODULE/shell_integration/zsh   Resources/shell_integration/iterm2_shell_integration.zsh
cp $SUBMODULE/shell_integration/nu    Resources/shell_integration/iterm2_shell_integration.nu
# it2.py is owned by the shell-integration repo (it is embedded into the scripts
# above and materialized on the remote). Copy it back for the app/tests.
cp $SUBMODULE/shell_integration/it2.py OtherResources/it2.py
DEST=$PWD/Resources/utilities
ALLDEST=$PWD/OtherResources/utilities

# The remote it2: a hashed copy of the interpreter plus a wrapper that execs it, both
# uploaded to the remote host at getshell (see ShellIntegrationInjection.files). The copy is
# named by content hash so an upgrade lands under a new name instead of being skipped by a
# file-exists check, and so a session can name the copy matching ITS iTerm2. The same hash is
# substituted into the wrapper's fallback and emitted as a header for the app to inject.
# The remote copy keeps the established ~/.iterm2/it2.<hash>.py name, which the
# shell-integration scripts already materialize the embedded blob to. Only the WRAPPER's
# fallback and the app's injected IT2_PY need the hash at build time; the hashed file itself
# is produced when it is uploaded (iTermRemoteIt2.hashedCopyURL), so the bundle keeps one
# stable it2.py reference instead of a new Xcode file reference on every change.
# The wrapper is built in the submodule (shell_integration/Makefile, from
# source/it2-wrapper.in) with the hash substituted, so it always matches the it2.py beside it.
IT2_PY_HASH=$(shasum -a 256 $SUBMODULE/shell_integration/it2.py | cut -c1-16)
cp $SUBMODULE/shell_integration/it2-wrapper Resources/it2-remote
chmod 755 Resources/it2-remote

# Install Shell Integration & Utilities unpacks utilities.tgz and aliases each name in the
# manifest. The archive also carries the Python it2 in it2-files (wrapper and hashed
# interpreter), which the installer copies to ~/.iterm2; it is not in the manifest, so it gets
# no alias. See +[iTermShellIntegrationWindowController utilitiesExtractionCommand].
STAGE=$(mktemp -d)
cp -p $SUBMODULE/utilities/* $STAGE/
mkdir -p $STAGE/it2-files/bin
cp -p Resources/it2-remote $STAGE/it2-files/bin/it2
cp -p $SUBMODULE/shell_integration/it2.py $STAGE/it2-files/it2.$IT2_PY_HASH.py
(cd $STAGE && tar cvfz $DEST/utilities.tgz *)
rm -rf $STAGE

pushd $SUBMODULE/utilities
echo * > $DEST/utilities-manifest.txt
cp * $ALLDEST
popd

# A Swift file rather than a header: iTermLatestVersionByShell.h is #included into an ObjC
# implementation, but this value is read from Swift, and Swift does not import an ObjC
# string-literal #define.
IT2_GENERATED="sources/ShellIntegration/iTermBundledIt2.swift"
echo "// DO NOT MODIFY - Generated by tools/copy_shell_integration.sh" > $IT2_GENERATED
echo "let iTermBundledIt2PyHash = \"$IT2_PY_HASH\"" >> $IT2_GENERATED

HEADER="sources/ShellIntegration/iTermLatestVersionByShell.h"
echo "// DO NOT MODIFY - Generated by tools/copy_shell_integration.sh" > $HEADER
echo "latestVersionByShell = @{" >> $HEADER
grep ShellIntegrationVersion= Resources/shell_integration/iterm2_shell_integration.* | sed -n 's/^.*ShellIntegrationVersion=\([^;]*\).*shell=\([a-z]*\).*$/    @"\2": @\1,/p' >> $HEADER
echo "};" >> $HEADER

