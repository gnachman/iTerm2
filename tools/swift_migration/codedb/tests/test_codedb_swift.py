class TimeoutTest(unittest.TestCase):
    def test_run_in_group_kills_the_whole_group_on_timeout(self):
        import time
        d = make_temp()
        marker = os.path.join(d, 'child.pid')
        status, err = codedb.run_in_group(['/bin/sh', '-c', 'sleep 300 & echo $! > "%s"; wait' % marker], timeout=1)
        self.assertEqual(status, codedb.TIMEOUT_STATUS)
        self.assertIn('timed out after 1 s', err)
        with open(marker) as f:
            pid = int(f.read())
        # The background child was in the group: it was killed with it (a
        # zombie until it is reaped counts as gone).
        deadline = time.time() + 60
        while True:
            state = subprocess.run(['ps', '-o', 'stat=', '-p', str(pid)], capture_output=True, text=True).stdout
            if not state.strip() or state.strip().startswith('Z') or time.time() > deadline:
                break
            time.sleep(0.1)
        self.assertTrue(not state.strip() or state.strip().startswith('Z'), state)

    def test_each_step_of_a_module_has_the_module_timeout(self):
        root, paths = make_swift_root()
        ctx = swiftdb.SwiftContext(paths, codedb.MIGRATION_SCOPE_TEXT, codedb.current_sdk()[0])
        timeouts = []

        def fake_run(cmd, capture=True, lock=None, stdout=None, timeout=None, cwd=None):
            timeouts.append(timeout)
            return codedb.TIMEOUT_STATUS, 'codedb: timed out after %d s' % timeout

        con = sqlite3.connect(paths.db)
        swiftdb.ensure_schema(con)
        con.close()
        ok, facts = swiftdb.extract_module(paths, ctx, ctx.modules[0], fake_run, [], log=lambda m: None)
        self.assertFalse(ok)
        self.assertEqual(len(timeouts), 1)
        self.assertTrue(0 < timeouts[0] <= swiftdb.MODULE_TIMEOUT_SECONDS == 900, timeouts)
        self.assertIn('timed out after', facts['failure'])


