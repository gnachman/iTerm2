class DeclarationTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.db = fixture_db()

    def decls(self, cls_name='FXShapes'):
        return dict((r[0], r[1:]) for r in rows(
            self.db, 'SELECT swift_name, selector, selector_source, derived_selector, selector_derived, '
                     'explicit_name, is_class_member FROM swift_objc_decl WHERE class_name = ?', (cls_name,)))

    def test_private_selectors_are_derived_or_taken_from_the_compiler(self):
        d = self.decls()
        self.assertEqual([(name, d[name][0], d[name][1]) for name, _, _ in DERIVED_SHAPES], DERIVED_SHAPES)
        self.assertEqual(d['pPlain()'][3:5], (1, 0))
        self.assertEqual(d['pRenamed(_:)'][3:5], (0, 1))
        self.assertEqual(d['pOne(label:)'][3:5], (0, 0))
        self.assertEqual(d['pClassThing()'][5], 1)

    def test_derivation_agrees_with_the_compiler_on_every_shape(self):
        d = self.decls()
        # Where the compiler gave the selector (USR or @objc name), the
        # derivation from the Swift name gives the same, but for @objc(name).
        self.assertEqual([(name, d[name][0], d[name][1]) for name, _ in USR_SHAPES],
                         [(name, sel, 'usr') for name, sel in USR_SHAPES])
        self.assertEqual([(name, d[name][2]) for name, _ in USR_SHAPES], USR_SHAPES)
        for name, sel, source in DERIVED_SHAPES:
            if source == 'objc_attr':
                self.assertEqual(d[name][2], sel, name)
        self.assertEqual(d['renamed(_:)'][:3], ('customName:', 'usr', 'renamed:'))
        self.assertEqual(len(USR_SHAPES) + len(DERIVED_SHAPES), 57)

    def test_kinds_and_properties(self):
        got = rows(self.db, "SELECT kind, swift_name, property_usr FROM swift_objc_decl WHERE class_name = 'FXShapes' "
                            "AND swift_name LIKE 'prop%' ORDER BY swift_name")
        self.assertEqual(got, [('property', 'prop', None),
                               ('getter', 'prop.get', 'c:@M@Fix@objc(cs)FXShapes(py)prop'),
                               ('setter', 'prop.set', 'c:@M@Fix@objc(cs)FXShapes(py)prop')])
        sub = rows(self.db, "SELECT selector, kind FROM swift_objc_decl WHERE swift_name = 'subscript' ORDER BY kind")
        self.assertEqual(sub, [('objectAtIndexedSubscript:', 'getter'), ('setObject:atIndexedSubscript:', 'setter')])

    def test_overrides_and_protocol_methods(self):
        got = rows(self.db, "SELECT swift_name, selector, is_override, overrides_usr FROM swift_objc_decl WHERE "
                            "class_name = 'FXSub' AND implicit = 0 ORDER BY swift_name")
        self.assertEqual(got, [('count', None, 1, None),
                               ('count.get', 'count', 1, 'c:objc(cs)FXWidget(im)count'),
                               ('count.set', 'setCount:', 1, 'c:objc(cs)FXWidget(im)setCount:'),
                               ('takeFocus()', 'takeFocus', 1, 'c:objc(cs)FXWidget(im)takeFocus')])
        self.assertEqual(rows(self.db, "SELECT swift_name, selector FROM swift_objc_decl WHERE class_name = 'FXDel' "
                                       "AND implicit = 0 ORDER BY swift_name"),
                         [('deinit()', 'dealloc'), ('fixtureDidChange(_:)', 'fixtureDidChange:'),
                          ('protoRequired(_:)', 'protoRequired:'), ('requiredThing(_:)', 'requiredThing:')])
        self.assertEqual(rows(self.db, "SELECT swift_name, selector FROM swift_objc_decl WHERE class_name = "
                                       "'FXSwiftProto' ORDER BY swift_name"),
                         [('protoOptional(with:)', 'protoOptionalWith:'), ('protoRequired(_:)', 'protoRequired:')])

    def test_deinit_is_dealloc(self):
        # An explicit deinit is -dealloc, written in the source. The deinit
        # the compiler declares for FXSub adds no -dealloc to the class (otool
        # -oV shows none), so it is not recorded.
        self.assertEqual(rows(self.db, "SELECT class_name, line, selector, implicit FROM swift_objc_decl WHERE "
                                       "swift_name = 'deinit()'"), [('FXDel', 83, 'dealloc', 0)])


def hand_document(path, body_items, version=('6', '4', FIXTURE_COMPILER)):
    """A small hand-written dump document for path."""
    import json
    return json.dumps({'_kind': 'source_file', 'filename': path,
                       'compiler_version': {'_kind': 'compiler_version', 'major': version[0], 'minor': version[1],
                                            'full': version[2]},
                       'items': body_items}).encode('utf-8') + b'\n'


def call_node(usr, start, type_='$syycD', key_wrapper=None):
    node = {'_kind': 'declref_expr', 'type': type_, 'range': {'start': start, 'end': start},
            'decl': {'_kind': 'decl_ref', 'base_name': 'takeFocus', 'decl_usr': usr}}
    return node


