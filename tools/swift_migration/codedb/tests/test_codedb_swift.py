def make_swift_root(swiftc_version=FIXTURE_COMPILER, real_compiler=None):
    """A scratch repository: an Objective-C file that sends takeFocus and
    reads Fixture.h, the Swift fixture module, a project in which target T
    compiles the .m and target Fix the Swift files, a compile database, the
    Objective-C side extracted, and a Swift capture whose driver command names
    a fake swiftc that reports swiftc_version (or real_compiler)."""
    d = make_temp()
    root = os.path.join(d, 'repo')
    os.makedirs(os.path.join(root, 'sources'))
    shutil.copytree(MODULE, os.path.join(root, 'swift'))
    with open(os.path.join(root, 'sources', 'fxuse.m'), 'w') as f:
        f.write('#import "../swift/Fixture.h"\nvoid use(FXWidget *w) { [w takeFocus]; w.count = 3; }\n')
    paths = base.make_paths(root)
    paths = codedb.Paths(root, db=paths.db, cdb=paths.cdb, extractor=base.EXTRACTOR,
                         swift_reader=READER, swift_work=os.path.join(d, 'swiftwork'),
                         swift_reader_prebuilt=PREBUILT_READER)
    swift_files = ['swift/' + f for f in FILES]
    base.write_project(root, {'T': ['sources/fxuse.m'], 'Fix': swift_files})
    import json
    meta = {'meta': True, 'build_settings_sha256': codedb.build_settings_digest(root)}
    args = base.clang_args(root, 'sources/fxuse.m', extra=('-isysroot', codedb.current_sdk()[0]))
    with open(paths.cdb, 'w') as f:
        f.write(json.dumps(meta) + '\n')
        f.write(json.dumps({'target': 'T', 'file': 'sources/fxuse.m', 'directory': root, 'arguments': args}) + '\n')
    codedb.update(paths, log=lambda m: None, swift=False)
    swiftc = real_compiler
    if swiftc is None:
        swiftc = os.path.join(d, 'bin', 'swiftc')
        os.makedirs(os.path.dirname(swiftc))
        with open(swiftc, 'w') as f:
            f.write('#!/bin/sh\necho "%s"\necho "Target: arm64-apple-macosx27.0.0"\n' % swiftc_version)
        os.chmod(swiftc, 0o755)
    file_list = os.path.join(d, 'Build', 'Variant-NoSanitizers', 'Fix.SwiftFileList')
    os.makedirs(os.path.dirname(file_list))
    with open(file_list, 'w') as f:
        f.write(''.join(os.path.join(root, x) + '\n' for x in swift_files))
    sdk = codedb.current_sdk()[0]
    sys.path.insert(0, FIXTURE)
    import make_dump
    args = make_dump.driver_command(swiftc, file_list, sdk)
    args[args.index('-import-objc-header') + 1] = os.path.join(root, 'swift', 'Fixture.h')
    log = os.path.join(d, 'build.log')
    write_log(log, [('Fix', 'Variant-NoSanitizers', args)])
    swiftdb.write_swift_capture(log, os.path.join(paths.fragments, 'swift'), log=lambda m: None)
    return root, paths


def read_fixture_into(root, paths):
    """Read the captured dump into paths.db as the module Fix, as update
    would, so that the module is current."""
    sys.path.insert(0, FIXTURE)
    ctx = swiftdb.SwiftContext(paths, codedb.MIGRATION_SCOPE_TEXT, codedb.current_sdk()[0])
    con = sqlite3.connect(paths.db)
    swiftdb.ensure_schema(con)
    con.close()
    m = ctx.modules[0]
    inputs = [(swiftdb.stored_path(f, root), swiftdb._file_sha256(f), 'swift') for f in m.files]
    status, out, err = run_reader(paths.db, root, fixture_dump(os.path.join(root, 'swift')), m.files, inputs=inputs,
                                  cmd_digest=ctx.cmd_digest(m), file_list_digest=swiftdb.file_list_digest(m),
                                  compiler=ctx.compiler)
    assert status == 0, err
    con = sqlite3.connect(paths.db)
    con.execute('UPDATE swift_unit SET reader_version = ?, migration_scope = ?',
                (swiftdb.swift_reader_source_digest(), codedb.MIGRATION_SCOPE_TEXT))
    con.commit()
    con.close()
    return ctx


def states_of(paths):
    ctx = swiftdb.SwiftContext(paths, codedb.MIGRATION_SCOPE_TEXT, codedb.current_sdk()[0])
    con = sqlite3.connect(paths.db)
    try:
        return dict((k, (v.state, v.reason)) for k, v in swiftdb.module_states(con, ctx, codedb.DigestCache(
            paths.root)).items())
    finally:
        con.close()


