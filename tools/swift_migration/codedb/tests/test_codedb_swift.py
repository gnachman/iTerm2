def write_log(path, entries):
    """A build log with SwiftDriver commands: [(target, variant, command args)]."""
    import shlex
    with open(path, 'w') as f:
        f.write('Command line invocation:\n    xcodebuild build\n\n')
        for target, variant, args in entries:
            f.write("SwiftDriver %s normal arm64 com.apple.xcode.tools.swift.compiler (in target '%s' from "
                    "project 'P')\n    cd /r\n    builtin-SwiftDriver -- %s\n\n" % (
                        target, target, ' '.join(shlex.quote(a.replace('/VARIANT/', '/%s/' % variant)) for a in args)))
            f.write('CompileC something\n\n')


