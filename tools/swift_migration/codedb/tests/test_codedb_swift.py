def fixture_dump(module_dir=MODULE):
    with gzip.open(os.path.join(FIXTURE, 'module.json.gz'), 'rb') as f:
        return f.read().decode('utf-8').replace('@FIXTURE@', module_dir).encode('utf-8')


def new_db(path):
    con = sqlite3.connect(path)
    swiftdb.ensure_schema(con)
    con.close()


def run_reader(db, root, data, files, inputs=(), extra=(), command=None, stderr_file=None, module='Fix',
               compiler=FIXTURE_COMPILER, cmd_digest='cmd', file_list_digest='list'):
    """Run the reader on data (stdin) or command; returns (status, stdout, stderr)."""
    d = os.path.dirname(db)
    files_path = os.path.join(d, 'files.txt')
    with open(files_path, 'w') as f:
        f.write(''.join(x + '\n' for x in files))
    inputs_path = os.path.join(d, 'inputs.tsv')
    with open(inputs_path, 'w') as f:
        f.write(''.join('%s\t%s\t%s\n' % i for i in inputs))
    cmd = [READER, '--db', db, '--root', root, '--module', module, '--target', module, '--cmd-digest', cmd_digest,
           '--file-list-digest', file_list_digest, '--files', files_path, '--inputs', inputs_path,
           '--compiler-version', compiler, '--migration-scope', 'sources/'] + list(extra)
    if stderr_file:
        cmd += ['--stderr-file', stderr_file]
    if command:
        cmd += ['--'] + command
    r = subprocess.run(cmd, input=None if command else data, capture_output=True)
    return r.returncode, r.stdout.decode(), r.stderr.decode()


def fixture_db():
    """A database with the fixture module read from the captured dump, the
    module's files referred to in place (root is the repository)."""
    d = make_temp()
    db = os.path.join(d, 'db.sqlite')
    new_db(db)
    status, out, err = run_reader(db, REPO, fixture_dump(), [os.path.join(MODULE, f) for f in FILES])
    assert status == 0, err
    return db


def rows(db, sql, args=()):
    con = sqlite3.connect(db)
    try:
        return con.execute(sql, args).fetchall()
    finally:
        con.close()


