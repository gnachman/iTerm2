def real_compiler():
    try:
        swiftc = subprocess.run(['xcrun', '--find', 'swiftc'], capture_output=True, text=True,
                                check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError) as e:
        return None, 'no Swift compiler (%s)' % e
    version = swiftdb.compiler_version(swiftc)
    if version != FIXTURE_COMPILER:
        return None, 'the compiler is %r; the expectations were written for %r' % (version, FIXTURE_COMPILER)
    return swiftc, None


def skip_unless_compiler(test):
    swiftc, why = real_compiler()
    if swiftc is None:
        sys.stderr.write('\nSKIPPED %s: %s\n' % (test.id(), why))
        test.skipTest(why)
    return swiftc


def write_project(root, files_by_target):
    objects = ['ROOT = {isa = PBXGroup; children = (); sourceTree = "<group>"; };']
    n = 0
    for target in sorted(files_by_target):
        build_files = []
        for f in sorted(files_by_target[target]):
            n += 1
            objects.append('F%d = {isa = PBXFileReference; path = "%s"; sourceTree = SOURCE_ROOT; };' % (n, f))
            objects.append('B%d = {isa = PBXBuildFile; fileRef = F%d; };' % (n, n))
            build_files.append('B%d' % n)
        objects.append('P_%s = {isa = PBXSourcesBuildPhase; files = (%s); };' % (target, ', '.join(build_files)))
        objects.append('T_%s = {isa = PBXNativeTarget; name = %s; buildPhases = (P_%s); };' % (target, target, target))
    write(os.path.join(root, 'iTerm2.xcodeproj', 'project.pbxproj'),
          '// !$*UTF8*$!\n{\n\tarchiveVersion = 1;\n\tobjects = {\n\t\t%s\n\t};\n\trootObject = ROOT;\n}\n'
          % '\n\t\t'.join(objects))


def write_capture(swiftc, root, files):
    """Write the project (target SIF compiles module/<files>) and a capture of
    SIF's driver command from a build log, as capture_compile_commands.sh
    writes it, next to root. Returns the fragments directory."""
    d = os.path.dirname(root)
    rel = ['module/' + f for f in files]
    write_project(root, {'SIF': rel})
    file_list = os.path.join(root, 'Build', 'Variant-NoSanitizers', 'SIF.SwiftFileList')
    write(file_list, ''.join(os.path.join(root, x) + '\n' for x in rel))
    sdk = codedb.current_sdk()[0]
    args = [swiftc, '-module-name', 'SIF', '-Onone', '@' + file_list, '-enable-testing', '-swift-version', '5',
            '-import-objc-header', os.path.join(root, 'module', 'Bridge.h'), '-sdk', sdk, '-target',
            'arm64-apple-macos13.0', '-g', '-c', '-j8', '-enable-batch-mode', '-incremental', '-emit-module',
            '-emit-module-path', os.path.join(root, 'Build', 'SIF.swiftmodule'), '-emit-objc-header',
            '-emit-objc-header-path', os.path.join(root, 'Build', 'SIF-Swift.h'), '-module-cache-path',
            '/nonexistent/ModuleCache.noindex', '-experimental-emit-module-separately', '-working-directory', root]
    log = os.path.join(d, 'build.log')
    write(log, "SwiftDriver SIF normal arm64 com.apple.xcode.tools.swift.compiler (in target 'SIF')\n    cd %s\n"
               "    builtin-SwiftDriver -- %s\n\n" % (root, ' '.join(shlex.quote(a) for a in args)))
    fragments = os.path.join(d, 'fragments')
    shutil.rmtree(fragments, ignore_errors=True)
    swiftdb.write_swift_capture(log, os.path.join(fragments, 'swift'), log=lambda m: None)
    return fragments


def make_root(swiftc, files=FILES, extra=None):
    """A scratch repository with the fixture module in module/ (and extra:
    {name: text} files beside it), a project whose target SIF compiles
    files, and a capture of SIF's driver command."""
    d = make_temp()
    root = os.path.join(d, 'repo')
    shutil.copytree(FIXTURE, os.path.join(root, 'module'))
    for name, text in (extra or {}).items():
        write(os.path.join(root, 'module', name), text)
    fragments = write_capture(swiftc, root, files)
    work = os.path.join(d, 'work')
    paths = codedb.Paths(root, fragments=fragments, swift_work=work)
    paths.swift_module_cache = MODULE_CACHE
    return root, paths


def run(paths, label, overlay=None, absent=(), accept_stale=False, sections=si.SECTIONS, keep_raw=False):
    work = os.path.join(paths.swift_work, 'SIF', label)
    os.makedirs(work, exist_ok=True)
    snap = os.path.join(paths.swift_work, 'SIF', label + '.snapshot')
    log = []
    r = si.snapshot_module(paths, 'SIF', work, snap, overlay=overlay, absent=absent, accept_stale=accept_stale,
                           sections=sections, log=log.append, check_other_compilers=False, keep_raw=keep_raw)
    return r, log


