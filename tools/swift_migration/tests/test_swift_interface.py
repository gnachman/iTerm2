class DiffTest(unittest.TestCase):
    BASE = [
        'objc\tW.-go\tmethod\t-\t- (void)go;',
        'objc\tW.title\tproperty\t-\t@property (nonatomic, copy) NSString * _Nullable title;',
        'swift\tW.f(_:)\tmethod\tinternal\tfunc f(_ x: Int)',
        'swift\tW.f(_:)\tmethod\tinternal\tfunc f(_ x: String)',
    ]

    def run_diff(self, old, new, old_inc=(), new_inc=(), allow=None, sections=None, allow_unused=False):
        d = make_temp()
        a, b = os.path.join(d, 'a'), os.path.join(d, 'b')
        write(a, snapshot_text(old, old_inc))
        write(b, snapshot_text(new, new_inc))
        out = io.StringIO()
        status = si.diff_snapshots(a, b, allow=allow, sections=sections, out=out, allow_unused=allow_unused)
        return status, out.getvalue()

    def main(self, argv):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            try:
                status = si.main(argv)
            except SystemExit as e:
                status = e.code
        return status, out.getvalue() + err.getvalue()

    def test_identical_is_0(self):
        status, out = self.run_diff(self.BASE, self.BASE)
        self.assertEqual(status, 0, out)
        self.assertIn('--- 0 added, 0 removed, 0 changed; 0 not allowed', out)

    def test_added_removed_changed_grouped_by_section_and_kind(self):
        new = [self.BASE[0].replace('go', 'went'),
               self.BASE[1].replace('_Nullable', '_Nonnull'), self.BASE[2], self.BASE[3]]
        status, out = self.run_diff(self.BASE, new)
        self.assertEqual(status, 1)
        self.assertEqual(out, (
            '=== objc: method (1 added, 1 removed, 0 changed)\n'
            '  removed            W.-go\n'
            '      before: - (void)go;\n'
            '  added              W.-went\n'
            '      after:  - (void)went;\n'
            '=== objc: property (0 added, 0 removed, 1 changed)\n'
            '  changed            W.title\n'
            '      before: @property (nonatomic, copy) NSString * _Nullable title;\n'
            '      after:  @property (nonatomic, copy) NSString * _Nonnull title;\n'
            '--- 1 added, 1 removed, 1 changed; 3 not allowed\n'))

    def test_an_overload_whose_type_changes_is_one_change(self):
        new = self.BASE[:3] + ['swift\tW.f(_:)\tmethod\tinternal\tfunc f(_ x: Substring)']
        status, out = self.run_diff(self.BASE, new)
        self.assertEqual(status, 1)
        self.assertIn('  changed            W.f(_:)\n      before: internal func f(_ x: String)\n'
                      '      after:  internal func f(_ x: Substring)\n', out)

    def test_allowances_and_expect_file(self):
        new = self.BASE + ['swift\tW.g()\tmethod\tprivate\tfunc g()', 'objc\tW.-added\tmethod\t-\t- (void)added;']
        status, out = self.run_diff(self.BASE, new, allow=si.Allowances(added=['swift:W.g()']))
        self.assertEqual(status, 1)
        self.assertIn('added (allowed)    W.g()', out)
        d = make_temp()
        p = os.path.join(d, 'expect')
        write(p, '# what the port adds\nadded swift:W.g()\nadded glob:objc:W.-add*\n')
        status, out = self.run_diff(self.BASE, new, allow=si.Allowances.from_file(p))
        self.assertEqual(status, 0, out)
        write(p, 'renamed x\n')
        with self.assertRaises(si.InterfaceError):
            si.Allowances.from_file(p)

    def test_an_allowance_or_expectation_that_matches_nothing_is_1(self):
        status, out = self.run_diff(self.BASE, self.BASE, allow=si.Allowances(added=['objc:Foo.-qux']))
        self.assertEqual(status, 1, out)
        self.assertIn('matched no difference: added objc:Foo.-qux', out)
        status, out = self.run_diff(self.BASE, self.BASE, allow=si.Allowances(added=['objc:Foo.-qux']),
                                    allow_unused=True)
        self.assertEqual(status, 0, out)
        d = make_temp()
        a, p = os.path.join(d, 'a'), os.path.join(d, 'expect')
        write(a, snapshot_text(self.BASE))
        write(p, 'removed glob:objc:Nothing.*\n')
        self.assertEqual(self.main(['diff', a, a, '--allow-added', 'objc:Foo.-qux'])[0], 1)
        self.assertEqual(self.main(['diff', a, a, '--allow-changed', 'objc:Foo.-qux'])[0], 1)
        status, out = self.main(['diff', a, a, '--expect', p])
        self.assertEqual(status, 1, out)
        self.assertIn('removed glob:objc:Nothing.*', out)
        self.assertEqual(self.main(['diff', a, a, '--expect', p, '--allow-unused'])[0], 0)
        for command in ('diff', 'check'):
            status, out = self.main([command, '--help'])
            self.assertIn('--allow-unused', out)

    def test_a_changed_item_is_not_allowed_by_an_added_or_removed_allowance(self):
        new = [self.BASE[0], self.BASE[1].replace('_Nullable', '_Nonnull')] + self.BASE[2:]
        status, out = self.run_diff(self.BASE, new, allow=si.Allowances(added=['objc:W.title'],
                                                                        removed=['objc:W.title']), allow_unused=True)
        self.assertEqual(status, 1, out)
        self.assertIn('  changed            W.title\n', out)

    def test_patterns_match_exactly_unless_they_say_glob(self):
        keyed = ['swift\tFoo<[Int]>.x\tproperty\tinternal\tvar x: [Int]?',
                 'swift\tW.g()\tmethod\tinternal\tfunc g()', 'swift\tW.h()\tmethod\tinternal\tfunc h()']
        status, out = self.run_diff(self.BASE, self.BASE + keyed, allow=si.Allowances(
            added=['swift:Foo<[Int]>.x', 'swift:W.g()', 'swift:W.h()']))
        self.assertEqual(status, 0, out)
        # Without glob: a ? is a character of the key.
        status, out = self.run_diff(self.BASE, self.BASE + keyed[1:], allow=si.Allowances(added=['swift:W.?()']),
                                    allow_unused=True)
        self.assertEqual(status, 1, out)
        self.assertNotIn('(allowed)', out)
        status, out = self.run_diff(self.BASE, self.BASE + keyed[1:], allow=si.Allowances(
            added=['glob:swift:W.?()']))
        self.assertEqual(status, 0, out)
        # A glob is anchored: it matches the whole SECTION:KEY.
        status, out = self.run_diff(self.BASE, self.BASE + keyed[1:], allow=si.Allowances(added=['glob:W.?()']),
                                    allow_unused=True)
        self.assertEqual(status, 1, out)

    def test_snapshots_of_another_module_or_compiler_are_refused_unless_allow_mixed(self):
        d = make_temp()
        a, b, c = os.path.join(d, 'a'), os.path.join(d, 'b'), os.path.join(d, 'c')
        write(a, snapshot_text(self.BASE, compiler='Swift 1'))
        write(b, snapshot_text(self.BASE, module='N', compiler='Swift 1'))
        write(c, snapshot_text(self.BASE, compiler='Swift 2'))
        for other, what in ((b, 'module'), (c, 'compiler')):
            status, out = self.main(['diff', a, other])
            self.assertEqual(status, 2, out)
            self.assertIn(what, out)
            self.assertIn('--allow-mixed', out)
