    def edited(self, label, edits):
        """Snapshot with {file in module/: [(old, new)]} applied in an overlay."""
        overlay = {}
        d = os.path.join(self.paths.swift_work, 'overlay-' + label)
        for name, pairs in edits.items():
            text = read(os.path.join(self.root, 'module', name))
            for old, new in pairs:
                self.assertIn(old, text)
                text = text.replace(old, new)
            dest = os.path.join(d, 'module', name)
            write(dest, text)
            overlay['module/' + name] = dest
        r, log = run(self.paths, label, overlay=overlay)
        self.assertEqual(r.status, 0, log)
        return r

