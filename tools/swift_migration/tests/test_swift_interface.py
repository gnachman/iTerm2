class JSONStreamTest(unittest.TestCase):
    def test_items_are_decoded_one_at_a_time_across_buffer_refills(self):
        doc = {'metadata': {'n': 12345}, 'symbols': [{'a': i, 'b': 'x}' * i, 'c': [1.5, -2, None]}
                                                       for i in range(50)],
               'relationships': [{'r': 'y'}, 7, 'str"ing', 123456789]}
        d = make_temp()
        path = os.path.join(d, 'x.json')
        write(path, json.dumps(doc, indent=1))
        for chunk in (1, 3, 7, 1 << 20):
            def items(key):
                with open(path) as f:
                    s = si.JSONStream(f, chunk=chunk)
                    s.expect('{')
                    out = []
                    while True:
                        k = s.value()
                        s.expect(':')
                        if s.peek() == '[':
                            out += [(k, v) for v in s.array_items()]
                        else:
                            out.append((k, s.value()))
                        c = s.peek()
                        s.pos += 1
                        if c == '}':
                            return out
            got = items(None)
            self.assertEqual([v for k, v in got if k == 'symbols'], doc['symbols'], chunk)
            self.assertEqual([v for k, v in got if k == 'relationships'], doc['relationships'], chunk)
            self.assertEqual([v for k, v in got if k == 'metadata'], [doc['metadata']], chunk)
        self.assertEqual(list(si.iter_top_array(path, 'relationships')), doc['relationships'])
        self.assertEqual(si.top_value(path, 'metadata'), doc['metadata'])

    def test_truncated_json_is_an_error(self):
        d = make_temp()
        path = os.path.join(d, 'x.json')
        write(path, '{"symbols": [{"a": 1}, {"b": ')
        with self.assertRaises(si.InterfaceError):
            list(si.iter_top_array(path, 'symbols'))


# --- The symbol graph, hand-written ----------------------------------------------------

def sym(usr, kind, path, decl, access='internal', location=True, **extra):
    s = {'kind': {'identifier': kind}, 'identifier': {'precise': usr}, 'pathComponents': path,
         'names': {'title': path[-1]}, 'declarationFragments': [{'kind': 'text', 'spelling': decl}],
         'accessLevel': access}
    if location:
        s['location'] = {'uri': 'file:///r/' + ('X.swift' if location is True else location),
                         'position': {'line': 1, 'character': 1}}
    s.update(extra)
    return s


class SymbolGraphTest(unittest.TestCase):
    def write_graph(self, symbols, relationships, name='M.symbols.json', d=None):
        d = d or make_temp()
        write(os.path.join(d, name), json.dumps({'metadata': {}, 'module': {'name': 'M'}, 'symbols': symbols,
                                                 'relationships': relationships}))
        return d

    def test_sections_kinds_requirements_conformances_and_extensions(self):
        symbols = [
            sym('c:@M@M@objc(cs)W', 'swift.class', ['W'], '@objc class W'),
            sym('s:1M1WC1fyyF', 'swift.method', ['W', 'f()'], 'func f()', access='private',
                availability=[{'domain': 'macOS', 'introduced': {'major': 14, 'minor': 2}}]),
            sym('s:1M1PP', 'swift.protocol', ['P'], 'protocol P'),
            sym('s:1M1PP1gyyF', 'swift.method', ['P', 'g()'], 'func g()'),
            sym('s:So8NSStringC1ME1hyyF', 'swift.method', ['NSString', 'h()'], 'func h()',
                swiftExtension={'extendedModule': 'Foundation', 'constraints': []}),
            sym('s:SQsE2neoiySbx_xtFZ::SYNTHESIZED::c:@M@M@objc(cs)W', 'swift.func.op', ['W', '!=(_:_:)'],
                'static func != ()', location=False),
            sym('c:objc(cs)O', 'swift.class', ['O'], 'class O', access='open', location=False),
            sym('c:objc(cs)O(im)doIt:', 'swift.method', ['O', 'do(it:)'], 'func do(it: String!)', access='open',
                location=False),
            sym('s:So5ColorV8rawValueABSgSi_tcfc', 'swift.init', ['Color', 'init(rawValue:)'],
                'init?(rawValue: Int)', access='public', location='B.h'),
        ]
        rels = [
            {'kind': 'requirementOf', 'source': 's:1M1PP1gyyF', 'target': 's:1M1PP'},
            {'kind': 'conformsTo', 'source': 'c:@M@M@objc(cs)W', 'target': 's:1M1PP'},
            {'kind': 'inheritsFrom', 'source': 'c:@M@M@objc(cs)W', 'target': 'c:objc(cs)NSObject',
             'targetFallback': 'ObjectiveC.NSObject'},
            {'kind': 'conformsTo', 'source': 'c:objc(cs)O', 'target': 's:SQ', 'targetFallback': 'Swift.Equatable'},
        ]
        d = self.write_graph(symbols, rels)
        got = sorted(si.entry_line(e) for e in si.iter_symbol_entries(d, 'M'))
        self.assertEqual(got, sorted([
            'swift\tW\tclass\tinternal\t@objc class W',
            'swift\tW.f()\tmethod\tprivate\tfunc f() @available(macOS, introduced: 14.2)',
            'swift\tP\tprotocol\tinternal\tprotocol P',
            'swift\tP.g()\trequirement\tinternal\tfunc g()',
            'swift\tNSString.h()\tmethod\tinternal\tfunc h() [extension]',
            'swift\tW : P\tconformance\t-\tW : P',
            'swift\tW : ObjectiveC.NSObject\tinheritance\t-\tW : ObjectiveC.NSObject',
            'import\tO\tclass\topen\tclass O',
            'import\tO.do(it:)\tmethod\topen\tfunc do(it: String!)',
            'import\tO : Swift.Equatable\tconformance\t-\tO : Swift.Equatable',
            'import\tColor.init(rawValue:)\tinit\tpublic\tinit?(rawValue: Int)',
        ]))
        only_import = sorted(e.section for e in si.iter_symbol_entries(d, 'M', sections=('import',)))
        self.assertEqual(set(only_import), {'import'})

    def test_an_extensions_where_constraints_are_part_of_the_text(self):
        s1 = sym('s:Sa1ME1xyyF', 'swift.method', ['Array', 'x()'], 'func x()',
                 swiftExtension={'extendedModule': 'Swift', 'constraints': [
                     {'kind': 'conformance', 'lhs': 'Element', 'rhs': 'Equatable'},
                     {'kind': 'sameType', 'lhs': 'Index', 'rhs': 'Int'}]})
        self.assertEqual(si.symbol_text(s1), 'func x() [extension where Element : Equatable, Index == Int]')
        s1['swiftExtension']['constraints'] = []
        self.assertEqual(si.symbol_text(s1), 'func x() [extension]')

    def test_extension_graphs_are_read_and_other_modules_are_not(self):
        d = self.write_graph([sym('s:1M1AV', 'swift.struct', ['A'], 'struct A')], [])
        self.write_graph([sym('s:SS1ME1xyyF', 'swift.method', ['String', 'x()'], 'func x()',
                              swiftExtension={'extendedModule': 'Swift'})], [], name='M@Swift.symbols.json', d=d)
        self.write_graph([sym('s:2MM1BV', 'swift.struct', ['B'], 'struct B')], [], name='MM.symbols.json', d=d)
        got = sorted(e.key for e in si.iter_symbol_entries(d, 'M'))
        self.assertEqual(got, ['A', 'String.x()'])


