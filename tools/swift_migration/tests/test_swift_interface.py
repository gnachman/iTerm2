def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)


def read(path):
    with open(path, 'r', encoding='utf-8') as f:
        return f.read()


def snapshot_text(lines, incomplete=(), sections=si.SECTIONS, module='M', compiler=None):
    head = [si.FORMAT_LINE, '# module: ' + module, '# sections: ' + ' '.join(sections)]
    if compiler:
        head.append('# compiler: ' + compiler)
    head += [si.INCOMPLETE_PREFIX + r for r in incomplete]
    return '\n'.join(head + sorted(lines)) + '\n'


