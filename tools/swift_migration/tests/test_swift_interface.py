class HeaderTest(unittest.TestCase):
    def test_every_declaration_of_the_module_part_is_a_line_and_the_preamble_is_not(self):
        got = sorted(si.entry_line(e) for e in si.normalize_objc_header(HEADER.splitlines()))
        self.assertEqual(got, sorted(HEADER_LINES))

    def test_member_order_and_category_split_do_not_matter(self):
        reordered = HEADER.replace('- (void)go;\n', '').replace('- (void)extensionMethod;\n',
                                                                 '- (void)extensionMethod;\n- (void)go;\n')
        self.assertEqual(si.normalize_objc_header(reordered.splitlines()),
                         si.normalize_objc_header(HEADER.splitlines()))

    def test_an_enum_forward_declaration_is_its_own_line_and_not_part_of_the_next_class(self):
        text = HEADER.replace('IB_DESIGNABLE\n', 'SWIFT_ENUM_FWD_DECL(NSInteger, Nested)\nIB_DESIGNABLE\n')
        got = sorted(si.entry_line(e) for e in si.normalize_objc_header(text.splitlines()))
        self.assertEqual(got, sorted(HEADER_LINES + [
            'objc\tNested\tenum-forward\t-\tSWIFT_ENUM_FWD_DECL(NSInteger, Nested)']))

    def test_selectors(self):
        cases = {
            '- (void)go;': 'go',
            '- (BOOL)use:(Foo * _Nonnull)t error:(NSError * _Nullable * _Nullable)error;': 'use:error:',
            '+ (instancetype)new SWIFT_UNAVAILABLE_MSG("-init is unavailable");': 'new',
            '- (void)a:(void (^ _Nonnull)(NSInteger (^)(void)))x b:(id)y SWIFT_WARN_UNUSED_RESULT;': 'a:b:',
            '- (NSInteger)doThing:(NSInteger)a with:(NSInteger)b SWIFT_WARN_UNUSED_RESULT;': 'doThing:with:',
        }
        for decl, sel in cases.items():
            self.assertEqual(si.objc_selector(decl), sel, decl)

    def test_property_names(self):
        cases = {
            '@property (nonatomic) NSInteger count;': ('count', False),
            '@property (nonatomic, class) NSInteger shared SWIFT_AVAILABILITY(macos,introduced=14);': ('shared', True),
            '@property (nonatomic, copy) void (^ _Nullable done)(BOOL);': ('done', False),
            '@property (nonatomic) NSInteger (* _Nonnull fn)(int);': ('fn', False),
            '@property (nonatomic, readonly) NSURL * _Nonnull URL;': ('URL', False),
        }
        for decl, want in cases.items():
            self.assertEqual(si.objc_property(decl), want, decl)


