class RevFileListTest(unittest.TestCase):
    """check --rev builds the REV side's file list from the revision: files
    deleted or renamed since REV are compiled on the REV side, files added
    since REV are not."""

    def setUp(self):
        self.swiftc = skip_unless_compiler(self)
        # Stray.swift is in another target at REV: deleting it must not add it
        # to SIF's REV side (it does not compile).
        self.root, self.paths = make_root(self.swiftc, files=FILES + ('Extra.swift',), extra={
            'Extra.swift': EXTRA_SWIFT, 'Stray.swift': 'this is not Swift\n'})
        project = read(os.path.join(self.root, 'iTerm2.xcodeproj', 'project.pbxproj'))
        write_project(self.root, {'SIF': ['module/' + f for f in FILES + ('Extra.swift',)],
                                  'Other': ['module/Stray.swift']})
        self.assertNotEqual(project, read(os.path.join(self.root, 'iTerm2.xcodeproj', 'project.pbxproj')))
        self.git = ['git', '-C', self.root, '-c', 'user.name=t', '-c', 'user.email=t@t', '-c',
                    'commit.gpgsign=false']
        subprocess.run(['git', 'init', '-q', self.root], check=True)
        write(os.path.join(self.root, '.gitignore'), 'Build/\n')
        subprocess.run(self.git + ['add', '-A'], check=True)
        subprocess.run(self.git + ['commit', '-qm', 'base'], check=True)

    def commit(self, files, message):
        """Commit the work tree, then capture SIF compiling module/<files>
        (with the project matching it, so that the capture is current)."""
        fragments = write_capture(self.swiftc, self.root, files)
        self.assertEqual(fragments, self.paths.fragments)
        subprocess.run(self.git + ['add', '-A'], check=True)
        subprocess.run(self.git + ['commit', '-qm', message], check=True)

    def check(self):
        work = os.path.join(os.path.dirname(self.paths.swift_work), 'check-work')
        real_make_paths = si.make_paths

        def make_paths(args):
            # The shared module cache (a second cache of the same modules
            # cannot be used beside it).
            paths, work_root = real_make_paths(args)
            paths.swift_module_cache = MODULE_CACHE
            return paths, work_root
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err), \
                unittest.mock.patch.object(si, 'make_paths', make_paths):
            status = si.main(['check', '--rev', 'HEAD~1', '--root', self.root, '--fragments', self.paths.fragments,
                              '--work', work, '--module', 'SIF', '--ignore-other-compilers'])
        return status, out.getvalue(), err.getvalue()

    def test_a_deleted_file_shows_as_removed(self):
        subprocess.run(self.git + ['rm', '-q', 'module/Extra.swift', 'module/Stray.swift'], check=True)
        write_project(self.root, {'SIF': ['module/' + f for f in FILES]})
        self.commit(FILES, 'delete')
        status, out, err = self.check()
        self.assertEqual(status, 1, out + err)
        self.assertIn('  removed            SIFExtra\n', out)
        self.assertIn('  removed            SIFExtra.-extraMethod:\n', out)
        self.assertIn(' 0 added, ', out)
        self.assertIn('added to the REV side\'s file list (in the module at REV, deleted or renamed since): '
                      'module/Extra.swift', err)
        self.assertNotIn('Stray', out + err)
        self.assertIn('Not detected', out)

    def test_a_renamed_file_changes_nothing(self):
        subprocess.run(self.git + ['mv', 'module/Extra.swift', 'module/Moved.swift'], check=True)
        self.commit(FILES + ('Moved.swift',), 'rename')
        status, out, err = self.check()
        self.assertEqual(status, 0, out + err)
        self.assertIn('--- 0 added, 0 removed, 0 changed; 0 not allowed\n', out)
        self.assertIn('added to the REV side\'s file list (in the module at REV, deleted or renamed since): '
                      'module/Extra.swift', err)
        self.assertIn('dropped from the REV side\'s file list (not in the tree at REV): module/Moved.swift', err)

    def test_a_renamed_and_changed_file_shows_only_the_change(self):
        subprocess.run(self.git + ['mv', 'module/Extra.swift', 'module/Moved.swift'], check=True)
        moved = os.path.join(self.root, 'module', 'Moved.swift')
        write(moved, read(moved).replace('extraMethod(_ x: Int)', 'extraMethod(_ x: Int32)'))
        self.commit(FILES + ('Moved.swift',), 'rename and change')
        status, out, err = self.check()
        self.assertEqual(status, 1, out + err)
        self.assertIn('--- 0 added, 0 removed, 2 changed; 2 not allowed\n', out)
        self.assertIn('  changed            SIFExtra.-extraMethod:\n', out)
        self.assertIn('  changed            SIFExtra.extraMethod(_:)\n', out)

    def test_an_added_file_shows_as_added(self):
        write(os.path.join(self.root, 'module', 'New.swift'),
              'import Foundation\n@objc class SIFNew: NSObject { @objc func n() {} }\n')
        self.commit(FILES + ('Extra.swift', 'New.swift'), 'add')
        status, out, err = self.check()
        self.assertEqual(status, 1, out + err)
        self.assertIn('  added              SIFNew\n', out)
        self.assertIn(' 0 removed, 0 changed;', out)
        self.assertIn('dropped from the REV side\'s file list (not in the tree at REV): module/New.swift', err)


